import { test } from 'node:test';
import assert from 'node:assert/strict';

test('owner permissions, account lifecycle and crop deletion against Firebase emulators', { skip: !process.env.FIRESTORE_EMULATOR_HOST || !process.env.FIREBASE_AUTH_EMULATOR_HOST, timeout: 120000 }, async () => {
  process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID = 'demo-agriguard-owner';
  const { adminServices } = await import('../src/lib/server/owner-auth');
  const { GET, POST } = await import('../src/app/api/owner/route');
  const community = await import('../src/app/api/community/route');
  const { ownerOverview, farmerDetail } = await import('../src/lib/server/owner-service');
  const { OWNER_EMAIL } = await import('../src/lib/owner-admin');
  const services = adminServices();
  const { auth, db } = services;
  await db.doc('account_controls/emulator-check').get();
  const testPassword = 'EmulatorOnly!2026';
  const owner = await auth.createUser({ uid: 'owner-test', email: OWNER_EMAIL, password: testPassword });
  await auth.setCustomUserClaims(owner.uid, { owner: true, admin: true });
  const farmer = await auth.createUser({ uid: 'farmer-test', email: 'farmer@example.test', password: testPassword });
  const other = await auth.createUser({ uid: 'other-farmer', email: 'other@example.test', password: testPassword });
  const signIn = async (email: string) => {
    const response = await fetch(`http://${process.env.FIREBASE_AUTH_EMULATOR_HOST}/identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=emulator`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email, password: testPassword, returnSecureToken: true }) });
    const result = await response.json();
    assert.ok(result.idToken, JSON.stringify(result.error));
    return result.idToken as string;
  };
  const ownerToken = await signIn(OWNER_EMAIL);
  const farmerToken = await signIn(farmer.email!);
  const request = (token?: string, action?: unknown, query = '') => new Request(`https://agri-guard-copy.vercel.app/api/owner${query}`, { method: action ? 'POST' : 'GET', headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(action ? { 'Content-Type': 'application/json', Origin: 'https://agri-guard-copy.vercel.app' } : {}) }, ...(action ? { body: JSON.stringify(action) } : {}) });
  const write = async (action: unknown, status = 200, token = ownerToken) => { const response = await POST(request(token, action)); const body = await response.json(); assert.equal(response.status, status, JSON.stringify(body)); return body; };
  assert.equal((await GET(request())).status, 401);
  assert.equal((await GET(request(farmerToken))).status, 403);
  assert.equal((await GET(request('fake-token'))).status, 401);
  const now = new Date().toISOString();
  await db.doc(`profiles/${farmer.uid}`).set({ uid: farmer.uid, phone: '', name: 'Original Farmer', location: 'Lahore', createdAt: now });
  await db.doc(`profiles/${other.uid}`).set({ uid: other.uid, phone: '', name: 'Other Farmer', createdAt: now });
  await db.doc(`users/${farmer.uid}/crops/crop-one`).set({ name: 'Wheat', nameKey: 'wheat', plantCount: 1, createdAt: now, updatedAt: now });
  await db.doc(`users/${farmer.uid}/crops/crop-one/plants/plant-one`).set({ name: 'Plant A', createdAt: now });
  await db.doc(`users/${farmer.uid}/crops/crop-one/plants/plant-one/records/report-one`).set({ reportId: 'report-one', createdAt: now });
  await db.doc(`users/${farmer.uid}/reports/report-one`).set({ uid: farmer.uid, cropId: 'crop-one', crop: 'Wheat', disease: 'Saved diagnosis', createdAt: now });
  await db.doc(`users/${farmer.uid}/notifications/diagnosis_report-one`).set({ createdAt: now });
  await db.doc(`users/${other.uid}/crops/keep`).set({ name: 'Tomato', createdAt: now });
  await db.doc(`account_presence/${farmer.uid}`).set({ lastSeenAt: now });
  const overview = await ownerOverview(services, '', 1, 'all');
  assert.equal(overview.stats.farmers, 3);
  assert.equal(overview.stats.crops, 2);
  assert.equal(overview.stats.reports, 1);
  assert.equal(overview.stats.online, 1);
  assert.equal((await ownerOverview(services, 'Lahore', 1, 'all')).total, 1);
  let detail = await farmerDetail(services, farmer.uid);
  await write({ action: 'profile.update', uid: farmer.uid, version: detail.profileVersion, name: 'Updated Farmer', location: 'Islamabad' });
  assert.equal((await auth.getUser(farmer.uid)).displayName, 'Updated Farmer');
  await write({ action: 'profile.update', uid: farmer.uid, version: detail.profileVersion, name: 'Stale edit', location: 'Lahore' }, 409);
  await write({ action: 'profile.update', uid: other.uid, version: 'missing', name: 'Attack', location: '' }, 403, farmerToken);
  await write({ action: 'account.delete', uid: owner.uid, confirmation: OWNER_EMAIL }, 403);
  await write({ action: 'account.suspend', uid: owner.uid }, 403);
  await write({ action: 'crop.update', uid: farmer.uid, cropId: 'crop-one', version: detail.crops[0].version, name: 'Spring Wheat', notes: 'Owner correction' });
  detail = await farmerDetail(services, farmer.uid);
  assert.equal(detail.crops[0].name, 'Spring Wheat');
  assert.equal((await db.doc(`users/${farmer.uid}/reports/report-one`).get()).data()?.crop, 'Wheat');
  // Community visibility is opt-in and never returns private records or contact details.
  assert.deepEqual((await (await community.GET(request(farmerToken))).json()).farmers, []);
  const share = async (action: unknown, status = 200) => {
    const response = await community.POST(request(farmerToken, action));
    const body = await response.json(); assert.equal(response.status, status, JSON.stringify(body));
  };
  await share({ action: 'profile.share', name: 'Public Farmer', city: 'Lahore', uid: other.uid }, 400);
  await share({ action: 'profile.share', name: 'Public Farmer', city: 'Lahore' });
  await db.doc(`users/${farmer.uid}/reports/report-one`).update({ status: 'Complete', symptoms: 'PRIVATE NOTES', imageUrl: 'PRIVATE PHOTO', plan: { steps: [{ title: 'Saved step', description: 'Saved care guidance' }] } });
  await share({ action: 'case.share', reportId: 'other-private-report', usedTreatment: '', progress: 'Not started' }, 404);
  await share({ action: 'case.share', reportId: 'report-one', usedTreatment: 'Farmer experience', progress: 'Improved' });
  const otherToken = await signIn(other.email!);
  const shared = await (await community.GET(request(otherToken, undefined, `?uid=${farmer.uid}`))).json();
  assert.deepEqual(Object.keys(shared.profile).sort(), ['city', 'name', 'uid', 'updatedAt']);
  assert.equal(shared.cases[0].usedTreatment, 'Farmer experience');
  assert.equal(shared.cases[0].carePlan[0].title, 'Saved step');
  assert.ok(!JSON.stringify(shared).includes('PRIVATE'));
  assert.ok(!JSON.stringify(shared).includes(farmer.email!));
  await share({ action: 'profile.hide' });
  assert.equal((await community.GET(request(otherToken, undefined, `?uid=${farmer.uid}`))).status, 404);
  assert.equal((await db.collection(`community_profiles/${farmer.uid}/cases`).get()).size, 0);
  await share({ action: 'profile.share', name: 'Public Farmer', city: 'Lahore' });
  await share({ action: 'case.share', reportId: 'report-one', usedTreatment: '', progress: 'Not started' });
  await write({ action: 'crop.delete', uid: farmer.uid, cropId: 'crop-one', version: detail.crops[0].version, confirmation: 'Wrong' }, 400);
  await write({ action: 'crop.delete', uid: farmer.uid, cropId: 'crop-one', version: detail.crops[0].version, confirmation: 'Spring Wheat' });
  for (const path of ['crops/crop-one', 'crops/crop-one/plants/plant-one', 'crops/crop-one/plants/plant-one/records/report-one', 'reports/report-one', 'notifications/diagnosis_report-one']) assert.equal((await db.doc(`users/${farmer.uid}/${path}`).get()).exists, false, path);
  assert.equal((await db.doc(`users/${other.uid}/crops/keep`).get()).exists, true);
  assert.equal((await db.collection(`community_profiles/${farmer.uid}/cases`).get()).size, 0);
  const firestoreUrl = `http://${process.env.FIRESTORE_EMULATOR_HOST}/v1/projects/demo-agriguard-owner/databases/(default)/documents`;
  const clientRead = (path: string) => fetch(`${firestoreUrl}/${path}`, { headers: { Authorization: `Bearer ${farmerToken}` } });
  assert.equal((await clientRead(`profiles/${farmer.uid}`)).status, 200);
  assert.equal((await clientRead(`profiles/${other.uid}`)).status, 403);
  assert.equal((await clientRead(`users/${other.uid}/crops/keep`)).status, 403);
  assert.equal((await clientRead('owner_audit')).status, 403);
  assert.equal((await clientRead(`community_profiles/${farmer.uid}`)).status, 403);
  const escalation = await fetch(`${firestoreUrl}/account_controls/${farmer.uid}`, { method: 'PATCH', headers: { Authorization: `Bearer ${farmerToken}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ fields: { disabled: { booleanValue: false } } }) });
  assert.equal(escalation.status, 403);
  await write({ action: 'account.suspend', uid: farmer.uid });
  assert.equal((await auth.getUser(farmer.uid)).disabled, true);
  assert.equal((await community.GET(request(farmerToken))).status, 401);
  assert.equal((await community.GET(request(otherToken, undefined, `?uid=${farmer.uid}`))).status, 404);
  assert.equal((await clientRead(`profiles/${farmer.uid}`)).status, 403);
  await write({ action: 'account.restore', uid: farmer.uid });
  assert.equal((await auth.getUser(farmer.uid)).disabled, false);
  await signIn(farmer.email!);
  await db.doc(`users/${farmer.uid}/crops/another/plants/child/records/saved`).set({ createdAt: now });
  await db.doc('marketplace/farmer-listing').set({ sellerId: farmer.uid });
  await db.doc('supplier_contacts/contact').set({ userId: farmer.uid });
  await write({ action: 'account.delete', uid: farmer.uid, confirmation: 'incorrect@example.test' }, 400);
  await write({ action: 'account.delete', uid: farmer.uid, confirmation: farmer.email });
  await assert.rejects(auth.getUser(farmer.uid));
  assert.equal((await db.doc(`profiles/${farmer.uid}`).get()).exists, false);
  assert.equal((await db.doc(`community_profiles/${farmer.uid}`).get()).exists, false);
  assert.equal((await db.doc(`users/${farmer.uid}/crops/another/plants/child/records/saved`).get()).exists, false);
  assert.equal((await db.doc('marketplace/farmer-listing').get()).exists, false);
  assert.equal((await db.doc('supplier_contacts/contact').get()).exists, false);
  assert.equal((await db.doc(`account_controls/${farmer.uid}`).get()).data()?.status, 'deleted');
  assert.equal((await auth.getUser(other.uid)).uid, other.uid);
  assert.ok((await db.collection('owner_audit').where('status', '==', 'success').get()).size >= 6);
  await auth.setCustomUserClaims(owner.uid, { admin: true });
  assert.equal((await GET(request(ownerToken))).status, 403, 'removed owner role invalidates old sessions');
  await db.terminate();
});
